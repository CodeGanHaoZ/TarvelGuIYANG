export type ItineraryStop = {
  placeId: string;
  at: number;
  duration: number;
  activity: string;
  tips: string[];
};
export type DayGuide = {
  summary: string;
  meals: string;
  stay: string;
  stayCost: [number, number];
  preparation: string[];
};
export type ItineraryPreset = {
  id: string;
  title: string;
  destination: string;
  image: string;
  intro: string;
  days: { title: string; guide: DayGuide; stops: ItineraryStop[] }[];
};
const stop = (
  placeId: string,
  time: string,
  duration: number,
  activity: string,
  ...tips: string[]
): ItineraryStop => {
  const [h, m] = time.split(':').map(Number);
  return { placeId, at: h * 60 + m, duration, activity, tips };
};
const guide = (
  summary: string,
  meals: string,
  stay: string,
  preparation: string[],
  last = false,
): DayGuide => ({
  summary,
  meals,
  stay,
  preparation,
  stayCost: last ? [0, 0] : [180, 320],
});

